class ScaffoldError(ValueError):
    """The probation source scaffold cannot be safely created."""


def _error_text(exc: BaseException) -> str:
    text = str(exc).strip()
    return text or type(exc).__name__


def _standard_temp_alias_ancestor(ancestor: Path, requested: Path) -> bool:
    """Allow only the OS alias chain leading to the standard temp directory."""
    temp_root = Path(tempfile.gettempdir())
    try:
        requested.relative_to(temp_root)
    except ValueError:
        return False
    resolved_temp_root = temp_root.resolve(strict=False)
    lexical_chain = (temp_root, *temp_root.parents)
    resolved_chain = (resolved_temp_root, *resolved_temp_root.parents)
    if ancestor not in lexical_chain:
        return False
    try:
        return ancestor.resolve(strict=False) in resolved_chain
    except (OSError, RuntimeError):
        return False


def _resolve_file(path: Path, label: str) -> Path:
    """Resolve an explicit file while rejecting unsafe symlink and hard-link paths.

    Config and temporary state directories are valid explicit destinations for
    this command. Unlike generic derived-artifact paths, their names are not
    treated as protected merely because they are named ``configs`` or
    ``state``. The command refuses arbitrary symlink ancestors and hard-linked
    destination files, while allowing the standard OS temporary-directory alias
    chain such as macOS ``/var`` to ``/private/var``.
    """
    requested = path if path.is_absolute() else Path.cwd() / path
    try:
        resolved = requested.resolve(strict=False)
    except (OSError, RuntimeError) as exc:
        raise ScaffoldError(f"cannot resolve {label}: {_error_text(exc)}") from exc
    for ancestor in (requested, *requested.parents):
        if ancestor.is_symlink() and not _standard_temp_alias_ancestor(ancestor, requested):
            raise ScaffoldError(f"{label} has a symlink ancestor")
        if ancestor.exists() and not ancestor.is_dir() and ancestor != requested:
            raise ScaffoldError(f"{label} parent must be a directory")
    if requested.is_symlink():
        raise ScaffoldError(f"{label} must not be a symlink")
    if resolved.exists():
        if not resolved.is_file():
            raise ScaffoldError(f"{label} must be a regular file")
        if resolved.stat().st_nlink != 1:
            raise ScaffoldError(f"{label} must not be a hard link")
    return resolved


def _require_existing_file(path: Path, label: str) -> Path:
    resolved = _resolve_file(path, label)
    if not resolved.exists():
        raise ScaffoldError(f"{label} does not exist: {path}")
    return resolved


def _load_json_file(path: Path, label: str) -> tuple[Path, bytes, Any]:
    resolved = _require_existing_file(path, label)
    try:
        raw = resolved.read_bytes()
        value = json.loads(raw.decode("utf-8"))
    except (OSError, UnicodeError, json.JSONDecodeError, TypeError) as exc:
        raise ScaffoldError(f"{label} is malformed JSON: {_error_text(exc)}") from exc
    return resolved, raw, value


def _serialize_json(value: Any) -> bytes:
    """Serialize without sorting keys so existing ordering semantics remain."""
    return (json.dumps(value, ensure_ascii=False, indent=2) + "\n").encode("utf-8")


def normalize_operator_metadata(metadata: Mapping[str, Any]) -> dict[str, Any]:
    """Validate and normalize metadata used for deterministic fixture generation."""
    if not isinstance(metadata, Mapping):
        raise ScaffoldError("operator metadata must be an object")
    result: dict[str, Any] = {}
    missing: list[str] = []
    for field in SOURCE_SCAFFOLD_REQUIRED_METADATA_FIELDS:
        value = metadata.get(field)
        if not isinstance(value, str) or not value.strip():
            missing.append(field)
        elif field == "lifecycle_note":
            # Validate the supplied note without changing its editor-facing
            # bytes. All other operator strings use their trimmed values.
            result[field] = value
        else:
            result[field] = value.strip()
    for field in SOURCE_SCAFFOLD_OPTIONAL_METADATA_FIELDS:
        value = metadata.get(field, "")
        if value is None:
            value = ""
        if not isinstance(value, str):
            raise ScaffoldError(f"optional operator metadata field {field} must be a string")
        result[field] = value.strip()
    for field in SOURCE_LAYOUT_FIELDS:
        if field not in metadata:
            continue
        value = metadata[field]
        if not isinstance(value, str) or not value.strip():
            raise ScaffoldError(f"operator metadata field {field} must be a nonblank string")
        result[field] = value.strip()
    if missing:
        raise ScaffoldError("explicit operator metadata is missing: " + ", ".join(missing))
    for field in ("contract_family", *RANKING_TABLE_FIELDS):
        if field not in metadata:
            continue
        value = metadata[field]
        if field == "contract_family":
            if not isinstance(value, str) or not value.strip():
                raise ScaffoldError(f"operator metadata field {field} must be a nonblank string")
            result[field] = value.strip()
            continue
        if field == "ranking_rank_source":
            if not isinstance(value, str) or value.strip().casefold() not in RANKING_RANK_SOURCES:
                raise ScaffoldError(f"{field} must be one of: {', '.join(RANKING_RANK_SOURCES)}")
            result[field] = value.strip().casefold()
        else:
            spec = RANKING_FIELD_SPECS_BY_NAME[field]
            if spec.value_kind == "list":
                if not isinstance(value, list) or any(not isinstance(item, str) or not item.strip() for item in value):
                    raise ScaffoldError(f"{field} must contain non-empty strings")
                result[field] = [item.strip() for item in value]
            elif spec.value_kind == "bool":
                if not isinstance(value, bool):
                    raise ScaffoldError(f"operator metadata field {field} must be a boolean")
                result[field] = value
            elif spec.value_kind == "int":
                if isinstance(value, bool) or not isinstance(value, int):
                    raise ScaffoldError(f"operator metadata field {field} must be an integer")
                if field == "ranking_detail_max_pages" and value > RANKING_DETAIL_MAX_PAGES:
                    raise ScaffoldError(f"ranking_detail_max_pages must not exceed {RANKING_DETAIL_MAX_PAGES}")
                result[field] = value
            elif not isinstance(value, str) or not value.strip():
                raise ScaffoldError(f"operator metadata field {field} must be a nonblank string")
            else:
                result[field] = value.strip()
            continue
    if result.get("contract_family", "").casefold() == "ranking-table":
        # An undated recurring ranking declares row movement instead of the
        # dated reporting-period trio, so the scaffold and
        # ``validate_ranking_contract_metadata`` must require the same set.
        dated_freshness_fields = () if ranking_undated_declared(result) else RANKING_DATED_FRESHNESS_FIELDS
        missing_ranking = [
            field
            for field in (
                "ranking_row_selector",
                "ranking_title_selector",
                "ranking_author_selector",
                "ranking_category_marker",
                *dated_freshness_fields,
                "ranking_evidence_url",
            )
            if not result.get(field)
        ]
        detail_fields = ranking_detail_requested_fields(result)
        if "category" not in detail_fields and not result.get("adult_nonfiction_exclusions"):
            missing_ranking.append("adult_nonfiction_exclusions")
        rank_source = str(result.get("ranking_rank_source", "selector")).strip().casefold()
        if rank_source == "selector" and not result.get("ranking_rank_selector"):
            missing_ranking.append("ranking_rank_selector when ranking_rank_source is selector")
        detail_supplies_isbn = "isbn" in detail_fields
        if not detail_supplies_isbn and not any(
            result.get(field)
            for field in (
                "ranking_identifier_selector",
                "ranking_identifier_attribute",
                "ranking_identifier_pattern",
            )
        ):
            missing_ranking.append(
                "one of ranking_identifier_selector, ranking_identifier_attribute, or ranking_identifier_pattern"
            )
        if missing_ranking:
            raise ScaffoldError("ranking-table metadata is missing: " + ", ".join(missing_ranking))
        ranking_error = validate_ranking_contract_metadata({**result, "metadata_ranking_table": True})
        if ranking_error:
            raise ScaffoldError(ranking_error)
    if result.get("contract_family", "").casefold() == "award-list":
        award_list_error = validate_award_list_declaration(result)
        if award_list_error:
            raise ScaffoldError(award_list_error)
    lifecycle_note = result["lifecycle_note"]
    if (
        re.search(r"(?<!\w)#\d+\b", lifecycle_note) is None
        or re.search(r"\breversible\b", lifecycle_note, flags=re.IGNORECASE) is None
    ):
        raise ScaffoldError(
            "lifecycle_note must include an onboarding issue reference and state that evaluation is reversible"
        )
    return result


def build_probation_replay_contract_metadata(metadata: Mapping[str, Any]) -> dict[str, Any]:
    """Build replay metadata from an already normalized operator mapping.

    The input has already passed the canonical operator-metadata validation,
    so this seam must copy that complete mapping instead of reconstructing a
    second metadata schema.
    Replay artifacts own an explicit lifecycle status, while an empty optional
    sort label remains omitted to preserve the established artifact shape.
    """
    if not isinstance(metadata, Mapping):
        raise ScaffoldError("normalized operator metadata must be an object")
    replay_metadata = dict(metadata)
    if replay_metadata.get("expected_sort_label") == "":
        replay_metadata.pop("expected_sort_label")
    replay_metadata["lifecycle_status"] = PROBATION_LIFECYCLE_STATUS
    return replay_metadata


