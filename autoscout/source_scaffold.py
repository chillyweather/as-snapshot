def _live_model_output_tokens(metadata: Mapping[str, Any]) -> int:
    """Use a full-rank budget only for bounded declarative ranking tables."""
    if str(metadata.get("contract_family", "")).strip().casefold() in {
        "bookinfo-weekly-json",
        "ipc-top40-csv",
        "award-list",
        "nuevoslibros-frontlist",
        "publisher-frontlist",
        "perlentaucher-daily-digest",
        "kirkus-coming-soon",
    }:
        return 8000
    if str(metadata.get("contract_family", "")).strip().casefold() != "ranking-table":
        return 1200
    expected_count = metadata.get("ranking_expected_raw_row_count")
    minimum_count = metadata.get("ranking_min_raw_row_count")
    maximum_count = metadata.get("ranking_max_raw_row_count")
    expected_is_bounded = (
        isinstance(expected_count, int) and not isinstance(expected_count, bool) and expected_count > 0
    )
    range_is_bounded = (
        isinstance(minimum_count, int)
        and not isinstance(minimum_count, bool)
        and minimum_count > 0
        and isinstance(maximum_count, int)
        and not isinstance(maximum_count, bool)
        and maximum_count >= minimum_count
    )
    return 8000 if expected_is_bounded or range_is_bounded else 1200


def _live_overlay(
    metadata: Mapping[str, Any], slug: str, helper_metadata_file: Path, config: Path, state_dir: Path
) -> dict[str, Any]:
    overlay = {
        "extraction_method": "agent-extraction-live",
        "enable_live": True,
        "extraction_backend": "real",
        "capture_live_response_file": f"{slug}-page-capture.json",
        "capture_extraction_response_file": f"{slug}-extraction-capture.json",
        "name": metadata["name"],
        "enable_real_backend": True,
        "credential_env": "AUTOSCOUT_AGENT_EXTRACTION_API_KEY",
        "max_model_input_chars": 120000,
        "model_timeout_seconds": 30,
        "model_max_output_tokens": _live_model_output_tokens(metadata),
        "helper_metadata_file": _fixture_relative_path(helper_metadata_file, config),
        "helper_metadata_sha256": metadata["helper_metadata_sha256"],
    }
    if str(metadata.get("contract_family", "")).strip().casefold() == "perlentaucher-daily-digest":
        # The digest reports a book once. Its seen-item index is weekly state, kept beside the Source Proposals.
        overlay["seen_guids_file"] = _fixture_relative_path(state_dir / f"{slug}-seen-items.json", config)
    if str(metadata.get("contract_family", "")).strip().casefold() == "kirkus-coming-soon":
        # The pre-collection pass writes its result outside the committed state, and the run's repository
        # preflight refuses any untracked or modified file. So the result is a machine-local file in an
        # ignored directory beside the fixtures, never weekly state; losing it costs only a repeated pass.
        overlay["kirkus_collection_file"] = _fixture_relative_path(
            helper_metadata_file.parent.parent / KIRKUS_COLLECTION_DIRECTORY / f"{slug}-collection.json", config
        )
        # The seen-item index is weekly state, kept beside the Source Proposals.
        overlay["seen_guids_file"] = _fixture_relative_path(state_dir / f"{slug}-seen-items.json", config)
    return overlay


def _source_list(raw: Mapping[str, Any], label: str) -> list[dict[str, Any]]:
    sources = raw.get("sources")
    if not isinstance(sources, list):
        raise ScaffoldError(f"{label} must contain a sources list")
    result: list[dict[str, Any]] = []
    for index, source in enumerate(sources):
        if not isinstance(source, Mapping):
            raise ScaffoldError(f"{label} source[{index}] must be an object")
        result.append(dict(source))
    return result


def _validate_portfolio_sources(raw: Mapping[str, Any], label: str) -> list[str]:
    names: list[str] = []
    seen: set[str] = set()
    for index, source in enumerate(_source_list(raw, label)):
        name = str(source.get("name", "")).strip()
        if not name:
            raise ScaffoldError(f"{label} source[{index}] has an invalid source name")
        if name in seen:
            raise ScaffoldError(f"{label} has duplicate source name: {name}")
        names.append(name)
        seen.add(name)
    return names


def _overlay_target(source: Mapping[str, Any], label: str, index: int, portfolio_names: set[str]) -> str:
    for key in ("name", "portfolio_name"):
        if key in source and (not isinstance(source[key], str) or not source[key].strip()):
            raise ScaffoldError(f"{label} overlay[{index}] has an invalid {key} identity")
    target = str(source.get("portfolio_name") or source.get("name") or "").strip()
    if not target:
        raise ScaffoldError(f"{label} overlay[{index}] has no source identity")
    if target not in portfolio_names:
        raise ScaffoldError(f"{label} overlay[{index}] names unknown source: {target}")
    # ``portfolio_name`` selects the base source. ``name`` is a supported
    # overlay override and may intentionally change the resolved source name.
    # Duplicate and sequence checks must continue to use the portfolio target.
    return target


def _validate_config_identities(
    raw: Mapping[str, Any], label: str, portfolio_names: set[str], portfolio_path: Path, config_path: Path
) -> list[str]:
    sources = _source_list(raw, label)
    if "weekly_portfolio" not in raw:
        return _validate_portfolio_sources(raw, label)
    portfolio_ref = raw["weekly_portfolio"]
    if not isinstance(portfolio_ref, str) or not portfolio_ref.strip():
        raise ScaffoldError(f"{label} has an invalid weekly_portfolio reference")
    try:
        referenced = (config_path.parent / portfolio_ref).resolve()
    except (OSError, RuntimeError) as exc:
        raise ScaffoldError(f"{label} weekly_portfolio reference cannot be resolved") from exc
    if referenced != portfolio_path:
        raise ScaffoldError(f"{label} weekly_portfolio does not reference the supplied portfolio")
    identities: list[str] = []
    seen: set[str] = set()
    for index, source in enumerate(sources):
        target = _overlay_target(source, label, index, portfolio_names)
        if target in seen:
            raise ScaffoldError(f"{label} has duplicate overlay identity: {target}")
        identities.append(target)
        seen.add(target)
    return identities


def _resolve_for_validation(raw: Mapping[str, Any], portfolio: Mapping[str, Any]) -> dict[str, Any]:
    if "weekly_portfolio" not in raw:
        return dict(raw)
    portfolio_sources = _source_list(portfolio, "portfolio")
    by_name = {str(source["name"]).strip(): source for source in portfolio_sources}
    resolved_sources: list[dict[str, Any]] = []
    for overlay in _source_list(raw, "config"):
        target = str(overlay.get("portfolio_name") or overlay.get("name") or "").strip()
        overlay_copy = dict(overlay)
        overlay_copy.pop("portfolio_name", None)
        resolved_sources.append({**by_name[target], **overlay_copy})
    result = dict(raw)
    result["sources"] = resolved_sources
    result.pop("weekly_portfolio", None)
    return result


def _validate_generated_config(raw: Mapping[str, Any], portfolio: Mapping[str, Any], label: str) -> None:
    errors = validate_config(_resolve_for_validation(raw, portfolio))
    if errors:
        raise ScaffoldError(f"{label} validation failed: {'; '.join(errors)}")


def _append_source(raw: Mapping[str, Any], source: Mapping[str, Any], overlay: Mapping[str, Any]) -> dict[str, Any]:
    result = dict(raw)
    sources = [dict(item) for item in _source_list(raw, "config")]
    if "weekly_portfolio" in raw:
        sources.append(dict(overlay))
    else:
        sources.append({**source, **dict(overlay)})
    result["sources"] = sources
    return result


def _existing_source_matches(raw: Mapping[str, Any], source: Mapping[str, Any], overlay: Mapping[str, Any]) -> bool:
    sources = _source_list(raw, "config")
    if "weekly_portfolio" in raw:
        return any(
            str(item.get("portfolio_name") or item.get("name") or "").strip() == source["name"]
            and dict(item) == dict(overlay)
            for item in sources
        )
    return any(dict(item) == {**source, **dict(overlay)} for item in sources)


def _prepare_bundle(
    *,
    paths: dict[str, Path],
    source: dict[str, Any],
    page_fixture: Path,
    extraction_fixture: Path,
    slug: str,
) -> tuple[list[Path], list[bytes], str]:
    config_values: dict[str, dict[str, Any]] = {}
    raw_values: dict[str, dict[str, Any]] = {}
    raw_bytes: dict[str, bytes] = {}
    for key in ("portfolio_config", "pilot_config", "pilot_live_config", "live_config"):
        _resolved, raw, value = _load_json_file(paths[key], key.replace("_", " "))
        if not isinstance(value, Mapping):
            raise ScaffoldError(f"{key.replace('_', ' ')} must be a JSON object")
        raw_values[key] = dict(value)
        raw_bytes[key] = raw

    portfolio = raw_values["portfolio_config"]
    portfolio_names = _validate_portfolio_sources(portfolio, "portfolio config")
    portfolio_name_set = set(portfolio_names)
    identities: dict[str, list[str]] = {}
    for key in ("pilot_config", "pilot_live_config", "live_config"):
        label = key.replace("_", " ")
        identities[key] = _validate_config_identities(
            raw_values[key], label, portfolio_name_set, paths["portfolio_config"], paths[key]
        )
        if identities[key] != portfolio_names:
            raise ScaffoldError(f"{label} source-name sequence does not match portfolio config sequence")
    _validate_generated_config(portfolio, portfolio, "portfolio config")

    helper_metadata_destination = page_fixture.parent / f"{slug}-helper-metadata.json"
    source = {
        **source,
        "helper_metadata_file": _fixture_relative_path(helper_metadata_destination, paths["portfolio_config"]),
    }
    pilot_overlay = _pilot_overlay(
        source, page_fixture, extraction_fixture, paths["pilot_config"], helper_metadata_destination
    )
    state_dir = paths["proposal_file"].parent
    pilot_live_overlay = _live_overlay(source, slug, helper_metadata_destination, paths["pilot_live_config"], state_dir)
    live_overlay = _live_overlay(source, slug, helper_metadata_destination, paths["live_config"], state_dir)
    overlays = {
        "pilot_config": pilot_overlay,
        "pilot_live_config": pilot_live_overlay,
        "live_config": live_overlay,
    }
    present = [source["name"] in portfolio_names, *[source["name"] in identities[key] for key in identities]]
    if any(present):
        if not all(present):
            raise ScaffoldError(f"duplicate source name or partial configuration bundle: {source['name']}")
        if not _existing_source_matches(portfolio, source, {}):
            raise ScaffoldError(f"duplicate source name: {source['name']}")
        for key, overlay in overlays.items():
            if not _existing_source_matches(raw_values[key], source, overlay):
                raise ScaffoldError(f"duplicate source name: {source['name']}")
        # The semantic bundle is already published. Preserve its exact bytes,
        # including any existing formatting, on an exact retry.
        return (
            [paths[key] for key in ("portfolio_config", "pilot_config", "pilot_live_config", "live_config")],
            [raw_bytes[key] for key in ("portfolio_config", "pilot_config", "pilot_live_config", "live_config")],
            "unchanged",
        )
    if source["name"] in set().union(*identities.values(), portfolio_names):
        raise ScaffoldError(f"duplicate source name: {source['name']}")

    config_values["portfolio_config"] = dict(portfolio)
    config_values["portfolio_config"]["sources"] = [*_source_list(portfolio, "portfolio config"), source]
    config_values["pilot_config"] = _append_source(raw_values["pilot_config"], source, pilot_overlay)
    config_values["pilot_live_config"] = _append_source(raw_values["pilot_live_config"], source, pilot_live_overlay)
    config_values["live_config"] = _append_source(raw_values["live_config"], source, live_overlay)
    for key, value in config_values.items():
        _validate_generated_config(value, config_values["portfolio_config"], key.replace("_", " "))
    output_keys = ("portfolio_config", "pilot_config", "pilot_live_config", "live_config")
    return [paths[key] for key in output_keys], [_serialize_json(config_values[key]) for key in output_keys], "created"


def run_scaffold_probation_source(
    *,
    probe_evidence: Path,
    page_fixture: Path,
    extraction_fixture: Path,
    helper_metadata_file: Path,
    proposal_file: Path,
    proposal_id: str,
    slug: str,
    portfolio_config: Path,
    pilot_config: Path,
    pilot_live_config: Path,
    live_config: Path,
    metadata: Mapping[str, Any],
) -> tuple[dict[str, Any], int]:
    """Validate and publish one offline probation-source configuration bundle.

    The retained helper metadata sidecar is validated through deterministic
    replay-pair generation before any configuration file can be published.
    """
    operator_metadata = _metadata(metadata)
    replay_contract_metadata = build_probation_replay_contract_metadata(operator_metadata)
    _validate_http_url(operator_metadata["url"])
    if not isinstance(proposal_id, str) or not proposal_id.strip():
        raise ScaffoldError("proposal_id must be nonblank")
    if not isinstance(slug, str) or not slug.strip():
        raise ScaffoldError("slug must be nonblank")
    paths = {
        "probe_evidence": _require_existing_file(probe_evidence, "probe evidence"),
        "helper_metadata": _require_existing_file(helper_metadata_file, "helper metadata"),
        "page_fixture": _require_existing_file(page_fixture, "page fixture"),
        "extraction_fixture": _require_existing_file(extraction_fixture, "extraction fixture"),
        "proposal_file": _require_existing_file(proposal_file, "Source Proposal file"),
        "portfolio_config": _require_existing_file(portfolio_config, "portfolio config"),
        "pilot_config": _require_existing_file(pilot_config, "pilot config"),
        "pilot_live_config": _require_existing_file(pilot_live_config, "pilot-live config"),
        "live_config": _require_existing_file(live_config, "live config"),
    }
    destination_paths = [paths[key] for key in ("portfolio_config", "pilot_config", "pilot_live_config", "live_config")]
    if len(set(destination_paths)) != len(destination_paths):
        raise ScaffoldError("configuration bundle destinations must be four different files")
    if paths["page_fixture"] == paths["extraction_fixture"]:
        raise ScaffoldError("page fixture and extraction fixture must be different files")
    input_paths = {
        paths["probe_evidence"],
        paths["helper_metadata"],
        paths["page_fixture"],
        paths["extraction_fixture"],
        paths["proposal_file"],
    }
    if set(destination_paths) & input_paths:
        raise ScaffoldError("configuration destination must not alias an input artifact")

    _evidence_path, _evidence_raw, evidence_value = _load_json_file(paths["probe_evidence"], "probe evidence")
    if not isinstance(evidence_value, Mapping):
        raise ScaffoldError("probe evidence must be a JSON object")
    evidence, verdict = _validate_probe_evidence(evidence_value, operator_metadata)
    try:
        pair = build_replay_fixture_pair(
            operator_metadata["url"],
            slug,
            evidence,
            source_name=operator_metadata["source_name"],
            signal_family=operator_metadata["signal_family"],
            contract_family=str(operator_metadata.get("contract_family", "")),
            contract_metadata=replay_contract_metadata,
            signal_strength=operator_metadata["expected_signal_strength"],
            candidate_category=operator_metadata["eligible_candidate_category"],
            language=operator_metadata["language"],
            expected_sort_label=operator_metadata.get("expected_sort_label", ""),
            helper_metadata_file=paths["helper_metadata"],
        )
    except ReplayFixtureError as exc:
        raise ScaffoldError(f"cannot build deterministic replay pair: {_error_text(exc)}") from exc
    page_bytes = paths["page_fixture"].read_bytes()
    extraction_bytes = paths["extraction_fixture"].read_bytes()
    if page_bytes != pair.page_bytes or extraction_bytes != pair.extraction_bytes:
        raise ScaffoldError(
            "supplied fixture pair is not the exact deterministic pair generated from evidence and operator metadata"
        )
    if pair.entry_count != len(pair.extraction["mentions"]) or not verdict.samples:
        raise ScaffoldError("deterministic replay pair has no accepted representative entries")

    _load_proposal(paths["proposal_file"], proposal_id, operator_metadata)
    source = _source_entry(
        operator_metadata,
        helper_metadata_file=paths["helper_metadata"],
        config_path=paths["portfolio_config"],
    )
    with bundle_write_lock(*destination_paths):
        output_paths, output_bytes, status = _prepare_bundle(
            paths=paths,
            source=source,
            page_fixture=paths["page_fixture"],
            extraction_fixture=paths["extraction_fixture"],
            slug=slug,
        )
        if status != "unchanged":
            try:
                for path in output_paths:
                    path.parent.mkdir(parents=True, exist_ok=True)
                publish_bundle(output_paths, output_bytes, replace=_staged_replace)
            except (OSError, SafeArtifactError) as exc:
                raise ScaffoldError(f"configuration bundle replacement failure: {_error_text(exc)}") from exc
    report = {
        "version": 1,
        "status": status,
        "source_name": operator_metadata["source_name"],
        "proposal_id": proposal_id,
        "url": operator_metadata["url"],
        "fixture_page": str(paths["page_fixture"]),
        "fixture_extraction": str(paths["extraction_fixture"]),
        "config_paths": {
            key: str(paths[key]) for key in ("portfolio_config", "pilot_config", "pilot_live_config", "live_config")
        },
        "entry_count": pair.entry_count,
        "operation_id": pair.operation_id,
        "capture_sha256": pair.capture_sha256,
        "exit_code": 0,
    }
    return report, 0


def scaffold_probation_source(**kwargs: Any) -> int:
    """Print structured JSON for the offline probation-source command."""
    try:
        report, code = run_scaffold_probation_source(**kwargs)
    except (OSError, ScaffoldError, ReplayFixtureError, SafeArtifactError, ValueError) as exc:
        print(json.dumps({"version": 1, "error": _error_text(exc)}, ensure_ascii=False, sort_keys=True))
        return 1
    print(json.dumps(report, ensure_ascii=False, sort_keys=True, indent=2))
    return code
