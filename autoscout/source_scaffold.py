def _validate_http_url(url: str) -> None:
    if any(character.isspace() for character in url):
        raise ScaffoldError("operator metadata url must be a valid HTTP(S) URL")
    try:
        parsed = urlsplit(url)
        _ = parsed.port
    except ValueError as exc:
        raise ScaffoldError("operator metadata url must be a valid HTTP(S) URL") from exc
    if parsed.scheme.casefold() not in {"http", "https"} or not parsed.netloc or not parsed.hostname:
        raise ScaffoldError("operator metadata url must be a valid HTTP(S) URL")


def _validate_probe_evidence(evidence: Mapping[str, Any], metadata: Mapping[str, Any]) -> tuple[dict[str, Any], Any]:
    if evidence.get("collection_mode") != "source-candidate-probe":
        raise ScaffoldError("probe evidence is not a retained source-candidate-probe capture")
    source_url = str(evidence.get("source_url", evidence.get("url", evidence.get("source_page", "")))).strip()
    if not source_url:
        raise ScaffoldError("probe evidence does not record the candidate URL")
    if normalized_url(source_url) != normalized_url(metadata["url"]):
        raise ScaffoldError("probe evidence is for a different URL than the operator metadata")
    for field in ("source_url", "url", "source_page"):
        if field in evidence and str(evidence[field]).strip():
            if normalized_url(str(evidence[field]).strip()) != normalized_url(metadata["url"]):
                raise ScaffoldError(f"probe evidence field {field} is for a different URL")
    if str(metadata.get("contract_family", "")).strip().casefold() == "ranking-table":
        expected_evidence = (
            "detail_page"
            if str(metadata.get("ranking_detail_fields", "")).strip()
            or str(metadata.get("ranking_detail_link_selector", "")).strip()
            else "source_page"
        )
        if str(metadata.get("ranking_evidence_url", "")).strip() != expected_evidence:
            raise ScaffoldError(f"ranking-table ranking_evidence_url must be exactly {expected_evidence}")
        if normalized_url(str(evidence.get("source_page", "")).strip()) != normalized_url(metadata["url"]):
            raise ScaffoldError("ranking-table source_page must match the operator URL")
    for field in ("source_name", "name"):
        if field in evidence:
            value = str(evidence[field]).strip()
            if not value:
                raise ScaffoldError(f"probe evidence field {field} is blank")
            if value != metadata["source_name"]:
                raise ScaffoldError("probe evidence source name is stale or does not match operator metadata")
    if "signal_family" in evidence:
        value = str(evidence["signal_family"]).strip()
        if value and value != metadata["signal_family"]:
            raise ScaffoldError("probe evidence signal family is stale or does not match operator metadata")
    evidence_contract = str(evidence.get("contract_family", "")).strip().casefold()
    metadata_contract = str(metadata.get("contract_family", "")).strip().casefold()
    if evidence_contract and metadata_contract != evidence_contract:
        raise ScaffoldError("probe evidence contract family is stale or does not match operator metadata")
    retained_metadata = evidence.get("contract_metadata")
    retained_declarations = dict(retained_metadata) if isinstance(retained_metadata, Mapping) else {}
    for field in (*SOURCE_LAYOUT_FIELDS, *RANKING_TABLE_FIELDS):
        if field in evidence:
            retained_declarations[field] = evidence[field]
    for field in ("visible_title_selector", "entry_scope_selector"):
        if evidence.get(field):
            retained_declarations[field] = evidence[field]
    for field, value in retained_declarations.items():
        if field in metadata and metadata[field] != value:
            raise ScaffoldError(f"probe evidence contract metadata field {field} is stale")

    source_metadata = dict(retained_declarations)
    source_metadata.update(
        {
            "url": metadata["url"],
            "contract_family": metadata_contract or evidence_contract,
            "visible_title_selector": str(
                evidence.get("visible_title_selector") or source_metadata.get("visible_title_selector", "")
            ),
            "entry_scope_selector": str(
                evidence.get("entry_scope_selector") or source_metadata.get("entry_scope_selector", "")
            ),
        }
    )
    try:
        verdict = evaluate_source_feasibility(source_metadata, evidence)
    except (TypeError, ValueError) as exc:
        raise ScaffoldError(f"probe evidence is malformed: {_error_text(exc)}") from exc
    if verdict.outcome != OUTCOME_ACCEPT:
        raise ScaffoldError(
            f"probe evidence is not accepted (outcome={verdict.outcome}, reason_code={verdict.reason_code})"
        )
    summary_error = validate_retained_summary(evidence, verdict)
    if summary_error is not None:
        _, reason = summary_error
        raise ScaffoldError(reason)
    if verdict.detected_heading.strip() != metadata["expected_page_heading"]:
        raise ScaffoldError("expected_page_heading does not match retained evidence")
    return dict(evidence), verdict


def _load_proposal(proposal_file: Path, proposal_id: str, metadata: Mapping[str, str]) -> None:
    _path, _raw, value = _load_json_file(proposal_file, "Source Proposal file")
    if isinstance(value, Mapping) and isinstance(value.get("proposals"), list):
        proposals = value["proposals"]
    elif isinstance(value, list):
        proposals = value
    else:
        raise ScaffoldError("Source Proposal file must contain a list of proposals")
    matches = [item for item in proposals if isinstance(item, Mapping) and item.get("id") == proposal_id]
    if len(matches) != 1:
        raise ScaffoldError(f"Source Proposal id was not found exactly once: {proposal_id}")
    proposal = matches[0]
    if proposal.get("status") != "accepted":
        raise ScaffoldError("Source Proposal must have accepted status")
    proposal_url = str(proposal.get("source_url", "")).strip()
    if not proposal_url or normalize_source_identity(proposal_url) != normalize_source_identity(metadata["url"]):
        raise ScaffoldError("Source Proposal identity does not match the operator URL")
    declared_identity = str(proposal.get("normalized_source", "")).strip()
    if declared_identity and declared_identity != normalize_source_identity(proposal_url):
        raise ScaffoldError("Source Proposal normalized identity is inconsistent")
    proposal_name = proposal.get("source_name")
    if isinstance(proposal_name, str) and proposal_name.strip():
        if proposal_name.strip() != metadata["source_name"]:
            raise ScaffoldError("Source Proposal name alignment does not match operator metadata")


def _source_entry(
    metadata: Mapping[str, Any], *, helper_metadata_file: Path | None = None, config_path: Path | None = None
) -> dict[str, Any]:
    contract = str(metadata.get("contract_family", "")).strip().casefold()
    entry: dict[str, Any] = {
        "name": metadata["source_name"],
        "family": metadata["family"],
        "url": metadata["url"],
        "active": True,
        "access_status": metadata["access_status"],
        "check_frequency": metadata["check_frequency"],
        "language": metadata["language"],
        "country": metadata["country"],
        "market": metadata["market"],
        "expected_category": metadata["expected_category"],
        "signal_family": metadata["signal_family"],
        "refresh_cadence": metadata["refresh_cadence"],
        "url_stability": metadata["url_stability"],
        "expected_page_heading": metadata["expected_page_heading"],
        "expected_signal_strength": metadata["expected_signal_strength"],
        "eligible_candidate_category": metadata["eligible_candidate_category"],
        "extraction_notes": metadata["extraction_notes"],
        "lifecycle_status": PROBATION_LIFECYCLE_STATUS,
        "lifecycle_note": metadata["lifecycle_note"],
        "notes": metadata["notes"],
    }
    if contract == "bookinfo-weekly-json":
        from autoscout.bookinfo_ranking import validate_declaration

        entry["contract_family"] = contract
        for field in ("bookinfo_period_evidence", "bookinfo_max_age_days", "adult_nonfiction_exclusions"):
            if field in metadata:
                entry[field] = metadata[field]
        validate_declaration(entry)
    elif contract == "ipc-top40-csv":
        from autoscout.ipc_top40_ranking import validate_declaration as validate_ipc_top40_declaration

        entry["contract_family"] = contract
        for field in ("ipc_top40_period_evidence", "ipc_top40_max_age_days", "adult_nonfiction_exclusions"):
            if field in metadata:
                entry[field] = metadata[field]
        validate_ipc_top40_declaration(entry)
    elif contract == "perlentaucher-daily-digest":
        from autoscout.perlentaucher_digest import DECLARATION_FIELDS as PERLENTAUCHER_DECLARATION_FIELDS
        from autoscout.perlentaucher_digest import validate_declaration as validate_perlentaucher_declaration

        entry["contract_family"] = contract
        for field in PERLENTAUCHER_DECLARATION_FIELDS:
            if field in metadata:
                entry[field] = metadata[field]
        validate_perlentaucher_declaration(entry)
    elif contract == "kirkus-coming-soon":
        from autoscout.kirkus_listing import DECLARATION_FIELDS as KIRKUS_DECLARATION_FIELDS
        from autoscout.kirkus_listing import validate_declaration as validate_kirkus_declaration

        entry["contract_family"] = contract
        for field in KIRKUS_DECLARATION_FIELDS:
            if field in metadata:
                entry[field] = metadata[field]
        validate_kirkus_declaration(entry)
    elif contract == "publisher-frontlist":
        # A dated publisher_card contract has its own strict page/mention battery;
        # generic exact-list rewrapping intentionally changes its identity.
        entry["contract_family"] = contract
    elif contract == "nuevoslibros-frontlist":
        # A dated card contract has its own strict page/mention battery;
        # generic exact-list rewrapping intentionally changes its identity.
        entry["contract_family"] = contract
    elif contract == "award-list":
        entry["contract_family"] = contract
        for field in ("visible_title_selector", *AWARD_LIST_FIELDS):
            if field in metadata and metadata[field] != "":
                entry[field] = metadata[field]
        award_list_error = validate_award_list_declaration(entry)
        if award_list_error:
            raise ScaffoldError(award_list_error)
    elif contract == "ranking-table":
        entry["contract_family"] = contract
        entry["metadata_ranking_table"] = True
        entry["ranking_evidence_url"] = str(metadata.get("ranking_evidence_url", "source_page"))
        for field in SOURCE_LAYOUT_FIELDS:
            if field != "expected_reporting_period" and field in metadata and metadata[field] != "":
                entry[field] = metadata[field]
        for field in RANKING_TABLE_FIELDS:
            if field in metadata and metadata[field] != "":
                entry[field] = metadata[field]
        if "adult_nonfiction_exclusions" in metadata:
            entry["adult_nonfiction_exclusions"] = list(metadata["adult_nonfiction_exclusions"])
    else:
        entry["metadata_exact_book_list"] = True
        if contract:
            entry["contract_family"] = contract
    if metadata.get("expected_sort_label"):
        entry["expected_sort_label"] = metadata["expected_sort_label"]
    if helper_metadata_file is not None:
        if config_path is None:
            raise ScaffoldError("helper metadata config path is required")
        entry["helper_metadata_file"] = _fixture_relative_path(helper_metadata_file, config_path)
        entry["helper_metadata_sha256"] = hashlib.sha256(helper_metadata_file.read_bytes()).hexdigest()
    return entry


def _fixture_relative_path(fixture: Path, config: Path) -> str:
    return Path(os.path.relpath(fixture, start=config.parent)).as_posix()


